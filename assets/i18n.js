/* ==========================================================================
   GYM BADGE — i18n engine (shared by the website and the PWA)

   One dictionary, one API, two surfaces. Every visible string in the app
   and on the site goes through a key. Switching language re-renders the
   current screen instantly and stores the choice for next time.

   Design rules
   ------------
   1. Translations are MEANING-IDENTICAL to the English source. The
      dictionary is keyed by the English phrase, so a missing entry can
      never silently change meaning — it falls back to English verbatim.
   2. Right-to-left languages (Arabic, Hebrew, Farsi, Urdu) flip the
      document direction automatically.
   3. The picker is a flags list — every language shows its flag first,
      then the language name in that language, then in English.
   4. Nothing depends on the network. The whole dictionary ships in the
      bundle so language switching works offline and in the installed PWA.

   Usage
   -----
     GBI18n.t("Workout")            -> localised string
     GBI18n.set("fr")               -> switch + persist + notify
     GBI18n.current()               -> { code, name, native, flag, dir }
     GBI18n.languages()             -> full picker list
     GBI18n.apply(root)             -> translate a DOM subtree in place
   ========================================================================== */
